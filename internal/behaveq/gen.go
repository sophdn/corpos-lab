	"answer directly as text."

// ExpansionArm is one model arm of the expansion study. The three arms share the
// conditions, materials, image, and sampler chain; they differ only in the model
// and its instruct wrapper. Ported from the gen_expansion_defs.ARMS entries.
type ExpansionArm struct {
	Key     string // the TOML basename ("mistral", "qwen38", "qwen2532")
	Name    string
	ModelID string
	Version string
	Wrapper string // instruct wrapper; {prompt} is the substitution point, \n are literal
	Note    string
}

