// Package behaveq ports the behavioral-equivalence-assay provenance scoring and
// generation python to Go (chain eradicate-python-rewrite-in-go). It backs the
// published paper "Duty or Corpus" (10.5281/zenodo.22716214).
//
// The four tools ported here mirror the python one-for-one:
//
//   - gen.go       — gen_expansion_defs.py: the study-def TOML generator.
//   - dp1.go       — dp1_rule_scorer.py: the deterministic DP-1 rule scorer.
//   - analyze.go   — analyze.py: the clear-rate + contrast statistics report.
//   - doublescore.go — double_score.py: the second-rater prompt/parse (pure parts).
//
// All logic is sans-IO: callers read the study's run/def files and pass the data
// in. cmd/corpos-lab/pubscore_behaveq.go does the file wiring.
package behaveq

