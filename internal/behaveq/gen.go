// ExpansionArmByKey returns the arm with the given key, or false when none match.
func ExpansionArmByKey(key string) (ExpansionArm, bool) {
	for _, a := range ExpansionArms {
		if a.Key == key {
			return a, true
		}
	}
	return ExpansionArm{}, false
}

// seedList builds the "1, 2, ..., n" seed string, matching python
// ", ".join(str(i) for i in range(1, n+1)).
func seedList(n int) string {
	parts := make([]string, 0, n)
	for i := 1; i <= n; i++ {
		parts = append(parts, strconv.Itoa(i))
	}
	return strings.Join(parts, ", ")
}

