func TestExtractModelBlock(t *testing.T) {
	cases := []struct {
		name string
		src  string
		want string
	}{
		{
			name: "basic block trims trailing blank before next section",
			src:  "name = \"x\"\n\n[model]\nbase_url = \"u\"\nmodel_id = \"m\"\n\n[materials]\nscenario = \"s\"\n",
			want: "[model]\nbase_url = \"u\"\nmodel_id = \"m\"\n",
		},
		{
			name: "block at end of file with trailing newline",
			src:  "[model]\nbase_url = \"u\"\n",
			want: "[model]\nbase_url = \"u\"\n",
		},
		{
			name: "block at end of file without trailing newline",
			src:  "[model]\nbase_url = \"u\"",
			want: "[model]\nbase_url = \"u\"\n",
		},
		{
			name: "interior blank lines are preserved",
			src:  "[model]\na = 1\n\nb = 2\n[materials]\n",
			want: "[model]\na = 1\n\nb = 2\n",
		},
		{
			name: "indented section header is trimmed then recognized",
			src:  "[model]\na = 1\n  [materials]\nb = 2\n",
			want: "[model]\na = 1\n",
		},
		{
			name: "no model section yields just a newline",
			src:  "name = \"x\"\n[materials]\nscenario = \"s\"\n",
			want: "\n",
		},
		{
			name: "empty source yields just a newline",
			src:  "",
			want: "\n",
		},
		{
			name: "crlf line endings are handled",
			src:  "[model]\r\nbase_url = \"u\"\r\n[materials]\r\n",
			want: "[model]\nbase_url = \"u\"\n",
		},
		{
			name: "content before model is skipped",
			src:  "# comment\nname = \"x\"\n[model]\nk = \"v\"\n[sampling]\n",
			want: "[model]\nk = \"v\"\n",
		},
	}
	for _, c := range cases {
		t.Run(c.name, func(t *testing.T) {
			if got := ExtractModelBlock(c.src); got != c.want {
				t.Errorf("ExtractModelBlock(%q)\n got %q\nwant %q", c.src, got, c.want)
			}
		})
	}
}

