func TestGenGridCellCountAndOrder(t *testing.T) {
	s := defaultSpec()
	s.Glyphs = []string{"g2", "g1"}
	s.Scenarios = []int{5, 3}
	cells := GenGrid(s)
	if len(cells) != 4 {
		t.Fatalf("got %d cells, want 4", len(cells))
	}
	want := []struct {
		glyph string
		scen  int
	}{{"g2", 5}, {"g2", 3}, {"g1", 5}, {"g1", 3}}
	for i, w := range want {
		if cells[i].Glyph != w.glyph || cells[i].Scenario != w.scen {
			t.Errorf("cell[%d] = %s/s%d, want %s/s%d", i, cells[i].Glyph, cells[i].Scenario, w.glyph, w.scen)
		}
	}
}

